#!/bin/sh
# Generate instance settings for the static dashboard.
#
# Cloudflare Pages: Build command `sh web/build.sh`, Build output directory `web`.
#
# Environment variables (both optional):
#   UMA_API_BASE  API base URL, e.g. https://uma.example.com
#                 (https://..., or http://localhost / http://127.0.0.1 for testing)
#   UMA_APP_ID    default app id, e.g. my-app
#
# Writes web/config.js and web/_headers (from _headers.template). With no
# variables set it reproduces the committed defaults: the API address is typed
# on the login screen and the CSP allows connections to any https: origin.
set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
API_BASE=${UMA_API_BASE:-}
APP_ID=${UMA_APP_ID:-}

die() { echo "build.sh: $*" >&2; exit 1; }

# Strip trailing slashes.
while [ "${API_BASE%/}" != "$API_BASE" ]; do API_BASE=${API_BASE%/}; done

if [ -n "$API_BASE" ]; then
  # Only safe URL characters, so the value can be embedded in JS and CSP as-is.
  printf '%s' "$API_BASE" | grep -Eq '^(https://[A-Za-z0-9.-]+|http://(localhost|127\.0\.0\.1))(:[0-9]{1,5})?(/[A-Za-z0-9._~/-]*)?$' ||
    die "UMA_API_BASE must look like https://host[:port][/path] (or http://localhost[:port]), got: $API_BASE"
  ORIGIN=$(printf '%s' "$API_BASE" | sed -E 's#^(https?://[^/]+).*#\1#')
  CONNECT_SRC="'self' $ORIGIN"
else
  # Unconfigured: allow any https API (plus local testing). Less strict, but
  # works for the plain "upload the folder" path.
  CONNECT_SRC="'self' https: http://localhost:* http://127.0.0.1:*"
fi

if [ -n "$APP_ID" ]; then
  printf '%s' "$APP_ID" | grep -Eq '^[a-z0-9._-]{1,64}$' ||
    die "UMA_APP_ID must be 1-64 chars of a-z, 0-9, '.', '_', '-', got: $APP_ID"
fi

cat > "$DIR/config.js" <<JS
// Instance settings for the dashboard. Generated by build.sh; empty values are
// filled in on the login screen / from /v1/apps.
window.UMA_CONFIG = {
  apiBase: "$API_BASE",
  appId: "$APP_ID",
};
JS

sed "s#__CONNECT_SRC__#$CONNECT_SRC#" "$DIR/_headers.template" > "$DIR/_headers"

echo "build.sh: apiBase=${API_BASE:-<empty>} appId=${APP_ID:-<empty>} connect-src=$CONNECT_SRC"
